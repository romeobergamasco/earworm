"""Publish the web app (web/) to a Hugging Face Static Space.

    python deploy/push_static.py <hf-username>/<space-name> <API URL>
    e.g. python deploy/push_static.py someone/earworm https://earworm-api.onrender.com

Copies web/ into a temporary folder, writes config.js with the API address and
the Space README, commits and pushes to https://huggingface.co/spaces/<...>.
Authentication is git's: username = Hugging Face username, password = an access
token with "write" permission (Git Credential Manager remembers it).
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]


def git(*args: str, cwd: Path) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[0].count("/") != 1:
        print(__doc__)
        return 2
    space, api = argv[0], argv[1].rstrip("/")
    if urlparse(api).scheme != "https":
        print("the API URL must start with https://")
        return 2
    if git("status", "--porcelain", "--", "web", cwd=ROOT).strip():
        print("uncommitted changes in web/; commit them first")
        return 1
    commit = git("rev-parse", "--short", "HEAD", cwd=ROOT).strip()
    with tempfile.TemporaryDirectory(prefix="earworm-static-") as tmp:
        out = Path(tmp)
        shutil.copytree(
            ROOT / "web", out, dirs_exist_ok=True, ignore=shutil.ignore_patterns("README.md")
        )
        (out / "config.js").write_text(
            f"// generated by deploy/push_static.py from commit {commit}\n"
            f'window.EARWORM_API = "{api}";\n',
            encoding="utf-8",
        )
        shutil.copy2(ROOT / "deploy" / "static-README.md", out / "README.md")
        git("init", "-q", "-b", "main", cwd=out)
        git("add", "-A", cwd=out)
        git(
            "-c", "user.name=Earworm deploy", "-c", "user.email=deploy@earworm.invalid",
            "commit", "-q", "-m", f"Deploy {commit}", cwd=out,
        )  # fmt: skip
        url = f"https://huggingface.co/spaces/{space}"
        print(f"pushing web/ of commit {commit} (API {api}) to {url} ...")
        subprocess.run(["git", "push", "--force", url, "main"], cwd=out, check=True)
    print(f"done: {url}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
